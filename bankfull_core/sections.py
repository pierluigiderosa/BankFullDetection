"""Cross-sections along a river axis.

Sections are straight lines perpendicular to the axis, every ``step`` along it, ``width``
long in total (half on each side). Each section goes from the hydrographic **left** bank to
the **right** bank, i.e. left and right looking in the direction of the axis: the axis must
be digitised from upstream to downstream. With a reversed axis the bankfull level does not
change, but left and right are swapped. See ``docs/sections.md``.

The idea comes from ``tools/XSGenerator.py`` of the legacy plugin (G. Allegri), with these
differences: ``width`` is the total length (the legacy used it per side); the direction is
averaged over a window along the axis instead of taken from the single segment; multi-part
axes are supported; the chainage is part of the result.
"""

import math
from dataclasses import dataclass
from numbers import Real

import numpy as np
import shapely
from shapely.geometry import LineString, MultiLineString
from shapely.geometry.base import BaseGeometry

# Relative tolerance on the part length when placing the last section.
_CHAINAGE_RTOL = 1e-9


@dataclass(frozen=True)
class Section:
    """A cross-section generated by ``generate_sections``.

    Attributes:
        index: position in the result, from 0, over all parts.
        part: index of the axis part (after merging contiguous parts), from 0.
        chainage: distance along the axis part from its first vertex [map units].
        center: (x, y) of the section on the axis.
        coords: ((x_left, y_left), (x_right, y_right)): the section line from the left to
            the right end, looking along the axis.
        azimuth: direction of the axis at the section [degrees clockwise from north,
            0 <= azimuth < 360], from the tangent window.
    """

    index: int
    part: int
    chainage: float
    center: tuple
    coords: tuple
    azimuth: float


def generate_sections(axis, step, width, *, offset=None, tangent_length=None):
    """Cross-sections perpendicular to a river axis.

    Args:
        axis: Shapely LineString or MultiLineString, or a sequence of (x, y) coordinates.
            Z values are ignored. Contiguous parts of a MultiLineString with the same
            direction are merged (``shapely.line_merge(directed=True)``); parts that stay
            separate are processed independently, numbered in input order, each with its
            own chainage from 0. Parts in opposite directions are never merged.
        step: distance between sections along the axis [map units], > 0.
        width: total length of each section [map units], > 0; ``width / 2`` on each side.
        offset: chainage of the first section, >= 0; default ``step / 2``, so that each
            section is at least ``step / 2`` from the ends of the part. Sections are at
            ``offset + k * step`` up to the part length. A part shorter than ``step``,
            or shorter than ``offset``, gets a single section at its midpoint.
        tangent_length: length of the window along the axis used for the direction,
            > 0; default ``step``. The tangent at chainage ``c`` is the vector between the
            axis points at ``c - tangent_length / 2`` and ``c + tangent_length / 2``,
            clamped to the ends of the part.

    Returns:
        Tuple of Section, ordered by part then chainage.

    Raises:
        ValueError: on invalid parameters or an empty, non-linear or zero-length axis.
    """
    step = _positive(step, "step")
    width = _positive(width, "width")
    offset = step / 2 if offset is None else _non_negative(offset, "offset")
    tangent_length = step if tangent_length is None else _positive(tangent_length,
                                                                    "tangent_length")
    parts = _axis_parts(axis)

    sections = []
    for part_index, line in enumerate(parts):
        length = line.length
        for chainage in _chainages(length, step, offset):
            center = line.interpolate(chainage)
            tx, ty = _tangent(line, chainage, tangent_length)
            # Left normal of the tangent (tx, ty) is (-ty, tx).
            half = width / 2
            cx, cy = float(center.x), float(center.y)
            left = (cx - ty * half, cy + tx * half)
            right = (cx + ty * half, cy - tx * half)
            azimuth = math.degrees(math.atan2(tx, ty)) % 360.0
            if azimuth >= 360.0:
                azimuth = 0.0
            sections.append(Section(index=len(sections), part=part_index,
                                    chainage=float(chainage), center=(cx, cy),
                                    coords=(left, right), azimuth=azimuth))
    return tuple(sections)


def _is_real(value):
    return isinstance(value, Real) and not isinstance(value, bool)


def _positive(value, name):
    if not _is_real(value) or not math.isfinite(value) or value <= 0:
        raise ValueError(f"{name} must be a finite number > 0, got {value!r}")
    return float(value)


def _non_negative(value, name):
    if not _is_real(value) or not math.isfinite(value) or value < 0:
        raise ValueError(f"{name} must be a finite number >= 0, got {value!r}")
    return float(value)


def _axis_parts(axis):
    """2D LineString parts of the axis, contiguous parts merged, in input order."""
    if isinstance(axis, BaseGeometry):
        geom = axis
    else:
        try:
            geom = LineString(axis)
        except (TypeError, ValueError, AttributeError, shapely.errors.ShapelyError) as exc:
            raise ValueError(f"axis must be a line or a sequence of (x, y) coordinates: "
                             f"{exc}") from exc
    if geom.geom_type not in ("LineString", "MultiLineString"):
        raise ValueError(f"axis must be a LineString or MultiLineString, got {geom.geom_type}")
    if geom.is_empty:
        raise ValueError("axis is empty")
    geom = shapely.force_2d(geom)
    originals = list(geom.geoms) if geom.geom_type == "MultiLineString" else [geom]
    for i, part in enumerate(originals):
        if part.is_empty or part.length == 0:
            raise ValueError(f"axis part {i} has zero length")
    if len(originals) == 1:
        return originals

    merged = shapely.line_merge(MultiLineString(originals), directed=True)
    merged = list(merged.geoms) if merged.geom_type == "MultiLineString" else [merged]
    # A directed merge starts every merged line at the start of an original part:
    # order the merged lines by the input index of that part.
    start_index = {}
    for i, part in enumerate(originals):
        start_index.setdefault(part.coords[0], i)
    merged.sort(key=lambda line: start_index.get(line.coords[0], len(originals)))
    return merged


def _chainages(length, step, offset):
    limit = length * (1 + _CHAINAGE_RTOL)
    if length < step or offset > limit:
        return np.array([length / 2])
    n = math.floor((limit - offset) / step) + 1
    return np.minimum(offset + step * np.arange(n), length)


def _tangent(line, chainage, window):
    """Unit tangent (tx, ty) of ``line`` at ``chainage`` over a window of length ``window``."""
    length = line.length
    a = line.interpolate(max(chainage - window / 2, 0.0))
    b = line.interpolate(min(chainage + window / 2, length))
    dx, dy = b.x - a.x, b.y - a.y
    norm = math.hypot(dx, dy)
    if norm <= 1e-12 * max(length, 1.0):
        # Window ends coincide (e.g. a closed loop as long as the window): local direction.
        eps = 1e-6 * length
        a = line.interpolate(max(chainage - eps, 0.0))
        b = line.interpolate(min(chainage + eps, length))
        dx, dy = b.x - a.x, b.y - a.y
        norm = math.hypot(dx, dy)
    return dx / norm, dy / norm
